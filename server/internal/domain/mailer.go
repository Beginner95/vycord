package domain

// MailMessage — готовое к отправке письмо. Порт намеренно ничего не знает про
// OTP: тема и тело собираются в юзкейсе, потому что содержание письма —
// прикладная политика, а транспорт — инфраструктура. Смена почтового
// провайдера не должна доходить до юзкейса.
//
// Названо MailMessage, а не Message, как в брифе задачи: имя Message уже
// занято чат-сообщением в message.go, и подстановка брифа один в один не
// компилируется. Следующим задачам (мейлер, юзкейс, HTTP) нужно
// ориентироваться на это имя, а не на текст брифа.
type MailMessage struct {
	To      string
	Subject string
	Text    string
	HTML    string
}

type Mailer interface {
	Send(msg MailMessage) error
}
